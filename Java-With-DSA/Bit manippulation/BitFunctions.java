
public class BitFunctions {

    public static void main (String args[]){
        // 1 :- Binary AND 

        System.out.println("1:- And function :- " + (5 & 6));

        // 2:- Binary OR 

        System.out.println("2:- Binary Or :- " + (5 | 6));

        // 3:- Binary XOR

        System.out.println("3:- Binary XOR:- " + (5 ^ 6));

        // 4:- Binary left
    }
    
}
